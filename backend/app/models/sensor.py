"""app/models/sensor.py — Pydantic models for soil sensor readings."""
from pydantic import BaseModel, Field
from typing import Optional
from datetime import datetime


class SensorDataIn(BaseModel):
    field_id: str
    soil_moisture: float = Field(..., ge=0, le=100,
        description="Volumetric water content as a percentage (0–100)")
    soil_temperature: float = Field(..., ge=-10, le=80,
        description="Soil temperature in degrees Celsius")
    soil_ph: float = Field(..., ge=0, le=14,
        description="Soil pH (0–14)")
    air_temperature: Optional[float] = Field(None, ge=-50, le=60)
    humidity: Optional[float] = Field(None, ge=0, le=100)
    simulated: bool = Field(default=False,
        description="True when data is generated by the simulator, not a physical sensor")


class SensorReadingOut(BaseModel):
    id: str
    field_id: str
    soil_moisture: float
    soil_temperature: float
    soil_ph: float
    air_temperature: Optional[float]
    humidity: Optional[float]
    simulated: bool
    timestamp: datetime


class SensorHistoryQuery(BaseModel):
    field_id: str
    limit: int = Field(default=50, ge=1, le=500)
    skip: int = Field(default=0, ge=0)
